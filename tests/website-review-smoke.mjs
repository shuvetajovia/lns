import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { startBrowser } from './browser-harness.mjs';
const app=await startBrowser({phoneVerification:true});
const {page,state,login,open}=app;
try {
  await mkdir('test-results',{recursive:true});
  await login('customer@example.com');
  await page.getByRole('button',{name:'Open Navigation'}).click();
  await page.getByRole('textbox',{name:'Search products in menu'}).fill('Rice');
  await page.getByRole('textbox',{name:'Search products in menu'}).press('Enter');
  await page.getByRole('heading',{name:'Search results for “Rice”'}).waitFor();
  assert.ok(await page.locator('.mn-product-card').count()>0);
  await page.getByRole('button',{name:'Open Navigation'}).click();
  await page.getByRole('textbox',{name:'Search products in menu'}).fill('Honey');
  await page.getByRole('textbox',{name:'Search products in menu'}).press('Enter');
  await page.getByRole('heading',{name:'Search results for “Honey”'}).waitFor();
  assert.ok(await page.locator('.mn-product-card').count()>0);
  await page.setViewportSize({width:1440,height:900});
  const search=page.getByRole('textbox',{name:'Search products',exact:true});
  await search.fill('zzznomatch');
  await page.getByText('No products found. Try another name or category.').waitFor();
  await search.fill('Rice');
  await page.screenshot({path:'test-results/review-search-desktop.png'});
  assert.ok((await search.boundingBox()).width>160);
  await search.press('Enter');
  await page.locator('.mn-product-card').first().getByRole('button',{name:/wishlist/i}).click();
  await page.getByTitle('Saved Ayurvedic Treasures').click();
  const wishlist=page.getByRole('dialog',{name:'Saved products'});
  await wishlist.getByText('In stock',{exact:true}).waitFor();
  assert.ok(await wishlist.locator('img').count()>0);
  await page.screenshot({path:'test-results/review-wishlist.png'});
  await page.keyboard.press('Escape');
  await open('/account');
  await page.getByLabel('Area / Locality',{exact:true}).fill('Gandhi Nagar');
  await page.getByLabel('Village / Town / City',{exact:true}).fill('Chennai');
  await page.getByLabel('Pincode',{exact:true}).fill('627004');
  await page.getByText('Delivery is unavailable for this pincode. Please check with the store.',{exact:true}).waitFor();
  const saves=state.requests.filter(r=>r.method==='PATCH').length;
  await page.getByRole('button',{name:'Save details'}).click();
  await page.waitForTimeout(200);
  assert.equal(state.requests.filter(r=>r.method==='PATCH').length,saves);
  await page.getByLabel('Pincode',{exact:true}).fill('600001');
  assert.equal(await page.getByLabel('District',{exact:true}).inputValue(),'Chennai');
  await page.getByRole('button',{name:'Save details'}).click();
  await page.locator('form').getByRole('status').filter({hasText:'Profile and address saved.'}).waitFor();
  assert.equal(state.profiles[state.email].address.locality,'Gandhi Nagar');
  for(const width of [320,390,768,1024,1280,1440]) {
    await page.setViewportSize({width,height:900});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`overflow ${width}`);
  }
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Save details'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:'test-results/review-address-mobile.png'});
  let verified=false;
  await page.route('**/rest/v1/rpc/is_my_phone_verified',route=>route.fulfill({contentType:'application/json',body:JSON.stringify(verified && route.request().postDataJSON().candidate.replace(/[ +]/g,'')==='919876543210')}));
  const authUser={id:'00000000-0000-4000-8000-000000000002',aud:'authenticated',role:'authenticated',email:'customer@example.com',user_metadata:{full_name:'Test Patron'}};
  await page.route('**/auth/v1/user',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({user:authUser})}));
  await page.route('**/auth/v1/verify',async route=>{
    const body=route.request().postDataJSON();
    assert.equal(body.type,'phone_change');
    if(body.token==='000000') return route.fulfill({status:403,contentType:'application/json',body:JSON.stringify({msg:'Invalid or expired code'})});
    verified=true;
    return route.fulfill({contentType:'application/json',body:JSON.stringify({user:authUser})});
  });
  await page.getByRole('button',{name:'Send SMS code'}).click();
  await page.getByLabel('SMS verification code').fill('000000');
  await page.getByRole('button',{name:'Verify mobile number'}).click();
  await page.getByText('Invalid or expired code',{exact:true}).waitFor();
  await page.getByLabel('SMS verification code').fill('123456');
  await page.getByRole('button',{name:'Verify mobile number'}).click();
  await page.getByText('Verified mobile number',{exact:true}).waitFor();
  await page.getByLabel('Mobile number',{exact:true}).fill('9876543211');
  await page.getByText('Mobile number not verified',{exact:true}).waitFor();
  assert.deepEqual(state.pageErrors,[]);
  console.log('PASS review mobile/repeated search, readable desktop results, wishlist, address validation/save and responsive layouts');
} finally { await app.close(); }
